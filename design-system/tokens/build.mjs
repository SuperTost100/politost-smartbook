// Writes tokens.css and ../theme/ptsb-tokens.ts from tokens.json, so the CSS and the antd theme
// cannot drift from the source. Run with `npm run tokens` after changing tokens.json.
// With --check it writes nothing and exits 1 when either file differs from what it would write.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

function themeBlock(mode) {
  const lines = [];
  for (const c of t.color.tokens) {
    lines.push(c.alias ? `  --${c.name}: var(--${c.alias});` : `  --${c.name}: ${c.value[mode]};`);
  }
  for (const s of t.shadow.tokens) lines.push(`  --${s.name}: ${s.value[mode]};`);
  return lines.join('\n');
}

const fontFaces = t.type.fonts
  .map((f) => `@font-face { font-family: '${f.family}'; src: url('../${f.file}') format('woff2-variations'); font-weight: ${f.weight}; font-style: ${f.style}; font-display: swap; }`)
  .join('\n');

const scalars = [
  ...Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`),
  ...[t.spacing, t.radius, t.size].flatMap((g) => g.tokens.map((s) => `  --${s.name}: ${s.value};`)),
].join('\n');

const covers = t.color.covers
  .map((c) => `.sb-cover-${c.name} { --cover: ${c.cover}; --cover-ink: ${c.ink}; }`)
  .join('\n');

const typeClasses = t.type.groups
  .flatMap((g) =>
    g.styles.map((s) => {
      const parts = [
        `font-family: var(--font-${g.family});`,
        `font-size: ${s.fontSize};`,
        `line-height: ${s.lineHeight};`,
        `font-weight: ${s.fontWeight};`,
        s.letterSpacing && `letter-spacing: ${s.letterSpacing};`,
        s.name === 'meta' && 'font-variant-numeric: tabular-nums;',
      ].filter(Boolean);
      return `.t-${s.name} { ${parts.join(' ')} }`;
    }),
  )
  .join('\n');

const css = `/* PoliTost Smartbook design tokens, direction Carta. Generated by build.mjs from tokens.json: edit the JSON, then run \`npm run tokens\`. */
${fontFaces}
:root, [data-theme="light"] {
  color-scheme: light;
${themeBlock('light')}
}
[data-theme="dark"] {
  color-scheme: dark;
${themeBlock('dark')}
}
:root {
${scalars}
}
${covers}
${typeClasses}
`;

const colorsOf = (mode) =>
  Object.fromEntries(t.color.tokens.filter((c) => !c.alias).map((c) => [camel(c.name), c.value[mode]]));
const shadowsOf = (mode) => Object.fromEntries(t.shadow.tokens.map((s) => [camel(s.name), s.value[mode]]));
const px = (name) => Number.parseInt(t.size.tokens.find((s) => s.name === name).value, 10);

const ts = `// Generated by design-system/tokens/build.mjs from tokens.json. Do not edit by hand.
export const ptsbColors = ${JSON.stringify({ light: colorsOf('light'), dark: colorsOf('dark') }, null, 2)} as const;

export const ptsbShadows = ${JSON.stringify({ light: shadowsOf('light'), dark: shadowsOf('dark') }, null, 2)} as const;

export const ptsbCovers = ${JSON.stringify(Object.fromEntries(t.color.covers.map((c) => [c.name, { cover: c.cover, ink: c.ink }])), null, 2)} as const;

export type PtsbCover = keyof typeof ptsbCovers;

export const FONT_SERIF = ${JSON.stringify(t.type.families.serif)};
export const FONT_SANS = ${JSON.stringify(t.type.families.sans)};
export const FONT_MONO = ${JSON.stringify(t.type.families.mono)};

export const ptsbLayout = {
  headerHeight: ${px('header-height')},
  siderWidth: ${px('sider-width')},
  railWidth: ${px('rail-width')},
  readingWidth: ${px('reading-width')},
  wideWidth: ${px('wide-width')},
} as const;
`;

const outputs = [
  [join(here, 'tokens.css'), css],
  [join(here, '../theme/ptsb-tokens.ts'), ts],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, text]) => !existsSync(file) || readFileSync(file, 'utf8') !== text);
  for (const [file] of stale) console.error(`stale: ${file}. Run npm run tokens.`);
  process.exit(stale.length ? 1 : 0);
}

for (const [file, text] of outputs) writeFileSync(file, text);
console.log('wrote tokens.css and theme/ptsb-tokens.ts');
